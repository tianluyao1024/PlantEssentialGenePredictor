def insert_after(paragraph, text: str, style: str) -> object:
    new = OxmlElement("w:p")
    paragraph._p.addnext(new)
    new_para = paragraph._parent.add_paragraph()
    new_para._p.getparent().remove(new_para._p)
    new_para._p = new
    new_para._element = new
    new_para.style = style
    new_para.add_run(text)
    return new_para


def replace_exact(doc: Document, old: str, new: str) -> None:
    for paragraph in doc.paragraphs:
        if paragraph.text == old:
            paragraph.text = new
            return
    raise RuntimeError(f"Could not find paragraph: {old[:80]}")


