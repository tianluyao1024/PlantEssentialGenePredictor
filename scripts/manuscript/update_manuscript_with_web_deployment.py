def replace_embedded_images(docx: Path) -> None:
    replacements = {
        "word/media/image1.png": FIGURES / "fig1_model_architecture_nature.png",
        "word/media/image2.png": FIGURES / "fig2_main_performance_nature.png",
        "word/media/image3.png": FIGURES / "fig3_feature_ablation_nature.png",
        "word/media/image4.png": FIGURES / "fig4_homology_and_delong_nature.png",
    }
    with tempfile.TemporaryDirectory() as temp_dir:
        temp = Path(temp_dir) / "repacked.docx"
        with zipfile.ZipFile(docx, "r") as source, zipfile.ZipFile(temp, "w", zipfile.ZIP_DEFLATED) as target:
            for item in source.infolist():
                if item.filename in replacements:
                    target.writestr(item, replacements[item.filename].read_bytes())
                else:
                    target.writestr(item, source.read(item.filename))
        shutil.move(temp, docx)


def main() -> None:
    shutil.copy2(SOURCE, OUTPUT)
    doc = Document(OUTPUT)
    update_text(doc)
    # Keep all figures within the document's 7.2-inch printable width and
    # preserve their true aspect ratios after their media parts are replaced.
    sizes = [(6.8, 4.0/7.2*6.8), (6.8, 2.55/7.2*6.8), (6.4, 2.65/7.2*6.4), (6.8, 2.55/7.2*6.8)]
    for shape, (width, height) in zip(list(doc.inline_shapes)[:4], sizes):
        shape.width = Inches(width)
        shape.height = Inches(height)
    doc.save(OUTPUT)
    replace_embedded_images(OUTPUT)
    print(OUTPUT)


if __name__ == "__main__":
    main()
